# R/freeze.R  --  Task 2.8, freeze the analytic file
#
# Merges the four built blocks into one row-per-hospital analytic file, hashes
# it, and pins the hash. After this point the file is FROZEN: any change requires
# a dated, numbered amendment in provenance/amendments.md and a version bump
# (analytic-v2.rds).
#
#   outcomes  Task 2.2   PSI-90 + components + reliability (v_i, tau2, lambda_i)
#   Block A   Task 2.3   hospital structure (10 covariates + flags)
#   Block B   Task 2.5   catchment-weighted context, 4 grain variants each
#   Block C   Task 2.7   admitted: cmi level/drift, contract labour (+ 20 MI
#                        draws), tort context. Gate results in
#                        output/tables/admission-gate-results.csv.
#
# The imputation was run at Task 2.7 with a fixed seed and its m = 20 completed
# vectors are IN Block C, so they are frozen here too -- the analytic file is a
# single self-contained hashed artifact, and Phase 3's MI / complete-case /
# omitted specification arms all read from it without re-running mice.
#
# data/analytic-v<N>.rds (v2 since amendment 1) is a build product (gitignored, regenerated by make.R).
# provenance/analytic-v1.sha256 is the committed, checked pin: make.R re-hashes
# the rebuilt file on every run and FAILS if it drifts. That is the freeze.
#
# Base R. Reads the Task 2.2-2.7 built files plus the crosswalk for identifiers.

source(file.path("R", "provenance.R"))

hdr <- function(s) cat("\n", strrep("=", 78), "\n", s, "\n", strrep("=", 78), "\n", sep = "")
sub_<- function(s) cat("\n--- ", s, " ---\n", sep = "")

## Amendment 1 (2026-10-01, Task S0.4): the file is now version 2. The pin file
## keeps its name and every version's lines; this stage checks the current one.
VERSION    <- "v2"
HASH_FILE  <- file.path("provenance", "analytic-v1.sha256")
AMEND_FILE <- file.path("provenance", "amendments.md")
OUT        <- file.path("data", paste0("analytic-", VERSION, ".rds"))

# ==========================================================================
hdr("TASK 2.8  freeze the analytic file")

o  <- readRDS(file.path("data", "outcomes.rds"))
a  <- readRDS(file.path("data", "blockA.rds"))
b  <- readRDS(file.path("data", "blockB.rds"))
cc <- readRDS(file.path("data", "blockC.rds"))
cw <- readRDS(file.path("data", "crosswalk.rds"))

frame <- o$ccn
N <- length(frame)
for (df in list(a, b, cc, cw)) stopifnot(setequal(frame, df$ccn), !anyDuplicated(df$ccn))
a  <- a[match(frame, a$ccn), ]
b  <- b[match(frame, b$ccn), ]
cc <- cc[match(frame, cc$ccn), ]
cw <- cw[match(frame, cw$ccn), ]

## identifiers from the crosswalk -- none of these names collide with the blocks
ID_COLS <- c("provider_number", "name", "state", "city", "zip5", "census_tract", "cbsa")
id <- cw[, ID_COLS]

## column-name collision guard, then a plain column bind in frame order
block_cols <- c(names(o)[-1], names(a)[-1], names(b)[-1], names(cc)[-1])
stopifnot(!anyDuplicated(c(ID_COLS, block_cols)))

analytic <- cbind(
  data.frame(ccn = frame, stringsAsFactors = FALSE),
  id,
  o[, setdiff(names(o), "ccn")],
  a[, setdiff(names(a), "ccn")],
  b[, setdiff(names(b), "ccn")],
  cc[, setdiff(names(cc), "ccn")]
)
rownames(analytic) <- NULL

## drop all-NA columns -- placeholders that document a gap (psi_software_version,
## the composite's Not-Applicable denominator) belong in the provenance notes,
## not the analysis-ready frozen file.
allna <- names(analytic)[vapply(analytic, function(x) all(is.na(x)), logical(1))]
if (length(allna)) {
  cat(sprintf("  dropping %d all-NA column(s): %s\n", length(allna), paste(allna, collapse = ", ")))
  analytic <- analytic[, setdiff(names(analytic), allna)]
}

## static provenance metadata -- NO timestamp (that would break the hash)
attr(analytic, "analytic_version") <- "v1"
attr(analytic, "analytic_blocks")  <- c(outcomes = "Task 2.2", blockA = "Task 2.3",
                                        blockB = "Task 2.5", blockC = "Task 2.7 (admitted)")
attr(analytic, "analytic_frame_n") <- N

sub_("the merge")
cat(sprintf("  %d hospitals x %d columns\n", nrow(analytic), ncol(analytic)))
cat(sprintf("  identifiers  %d   outcomes %d   Block A %d   Block B %d   Block C %d\n",
            1 + length(ID_COLS), ncol(o) - 1, ncol(a) - 1, ncol(b) - 1, ncol(cc) - 1))
cat(sprintf("  every frame CCN present exactly once: %s\n",
            if (setequal(analytic$ccn, frame) && !anyDuplicated(analytic$ccn)) "yes" else "NO"))
cat(sprintf("  no all-NA columns: %s\n",
            if (!any(vapply(analytic, function(x) all(is.na(x)), logical(1)))) "yes" else "NO"))

# ==========================================================================
# hash + freeze
# ==========================================================================
saveRDS(analytic, OUT, compress = "gzip")
h_file <- sha256_file(OUT)
## a compression-independent hash of the serialised object, in case a future
## R or zlib changes the container bytes without changing the data
ser <- tempfile(); writeBin(serialize(analytic, NULL, version = 3), ser)
h_obj <- sha256_file(ser)

sub_("hash")
cat(sprintf("  %-27s sha256  %s\n", OUT, h_file))
cat(sprintf("  serialised object (v3)      sha256  %s\n", h_obj))

reproduced <- NA
if (file.exists(HASH_FILE)) {
  rec <- readLines(HASH_FILE)
  ## a new version is pinned only on request (FREEZE_PIN=1), after its amendment
  ## is written; otherwise a version with no pin fails like any other drift
  if (!any(grepl(paste0("analytic-", VERSION, ".rds"), rec, fixed = TRUE)) &&
      identical(Sys.getenv("FREEZE_PIN"), "1")) {
    rec <- c(rec, paste0(h_file, "  data/analytic-", VERSION, ".rds"),
             paste0(h_obj, "  serialised-object-v3  analytic-", VERSION))
    writeLines(rec, HASH_FILE)
    cat(sprintf("\n  FREEZE_PIN=1 -- pinned %s in %s\n", OUT, HASH_FILE))
  }
  vline <- function(pat) grep(pat, rec, value = TRUE, fixed = TRUE)
  rec_file <- sub("^([0-9a-f]{64}).*", "\\1", vline(paste0("data/analytic-", VERSION, ".rds"))[1])
  rec_obj  <- sub("^([0-9a-f]{64}).*", "\\1", vline(paste0("serialised-object-v3  analytic-", VERSION))[1])
  reproduced <- identical(h_obj, rec_obj)
  cat(sprintf("\n  recorded serialised-object hash: %s\n", rec_obj))
  cat(sprintf("  REPRODUCTION TEST: rebuilt file %s the frozen hash\n",
              if (reproduced) "MATCHES" else "*** DOES NOT MATCH ***"))
  if (!reproduced && identical(h_file, rec_file))
    cat("  (the .rds container drifted but the serialised object is unchanged -- data is intact;\n   re-pin the file hash if the R/zlib version changed deliberately)\n")
} else {
  writeLines(c(
    "# Analytic file freeze -- Task 2.8. These hashes are the pin; make.R re-checks them.",
    paste0(h_file, "  data/analytic-v1.rds"),
    paste0(h_obj,  "  serialised-object-v3")),
    HASH_FILE)
  cat(sprintf("\n  first freeze -- wrote %s\n", HASH_FILE))
  reproduced <- TRUE
}

# ==========================================================================
# the amendment procedure
# ==========================================================================
if (!file.exists(AMEND_FILE)) {
  writeLines(c(
"# Analytic file amendments",
"",
"**Frozen:** 2026-08-31 at Task 2.8. `data/analytic-v1.rds`, hash pinned in",
"`provenance/analytic-v1.sha256`. `make.R` re-hashes the rebuilt file on every",
"run and fails if it drifts.",
"",
"---",
"",
"## The rule",
"",
"After the freeze, **any change to the contents of the analytic file requires a",
"dated, numbered amendment appended to this file**, stating:",
"",
"1. **What changed** -- which column(s), which hospitals, the old and new values",
"   or the nature of the change.",
"2. **Why** -- the defect or new information that forced it.",
"3. **What had been seen at the time** -- specifically, whether any modelling",
"   result that the change could affect had already been computed. Changing the",
"   analytic file after seeing a result it influences is not permitted; the",
"   amendment must state that no such result had been seen, or the change is",
"   invalid.",
"4. **The new version and hash** -- the file becomes `analytic-v2.rds` (then",
"   `-v3`, ...), `provenance/analytic-v1.sha256` gains the new line, and every",
"   downstream task re-runs against the new version.",
"",
"A change that only *adds* a column derived entirely from already-frozen columns",
"(a transformation, an interaction) does **not** need an amendment -- it is a",
"modelling choice, made in Phase 3, on top of the frozen file. An amendment is",
"for changing what the frozen file *records*: a corrected value, a re-drawn",
"imputation, an added or removed covariate, a changed frame.",
"",
"The admission gates (`provenance/admission-gates.md`) have their own, stricter",
"amendment rule for thresholds; that rule is unchanged and takes precedence for",
"anything it covers.",
"",
"---",
"",
"## Amendments",
"",
"*None. The file is as frozen at Task 2.8.*"),
    AMEND_FILE)
  cat(sprintf("  wrote %s (empty, rules stated)\n", AMEND_FILE))
} else {
  cat(sprintf("  %s already present -- not overwritten\n", AMEND_FILE))
}

# ==========================================================================
# exclusion-log completeness  (Phase 2 closes when this and the hash are good)
# ==========================================================================
sub_("exclusion log")
gates <- read.csv(file.path("output", "tables", "admission-gate-results.csv"),
                  colClasses = "character")
CONDITIONAL <- "C2.e"
hard_fail <- gates$gate_id[gates$pass == "FALSE" & !gates$gate_id %in% CONDITIONAL]
prov <- prov_read()
excl <- prov[nzchar(prov$exclusion_reason), c("source_id", "exclusion_reason")]
cat(sprintf("  hard-failed admission gates: %s\n",
            if (length(hard_fail)) paste(hard_fail, collapse = ", ") else "none"))
cat(sprintf("  sources.csv exclusion rows: %d  (%s)\n", nrow(excl),
            paste(excl$source_id, collapse = ", ")))
missing_excl <- character(0)
for (g in hard_fail) if (!any(grepl(g, prov$exclusion_reason))) missing_excl <- c(missing_excl, g)
cat(sprintf("  every hard-failed gate has an exclusion row: %s\n",
            if (!length(missing_excl)) "yes (vacuously -- nothing failed)" else paste("NO --", paste(missing_excl, collapse = ", "))))
cat("  C2.e is a conditional gate (A1), not an exclusion -- contract labour is admitted.\n")

# ==========================================================================
hdr("PHASE 2 CLOSE")
cat(sprintf("  analytic file      %s   %d x %d\n", OUT, nrow(analytic), ncol(analytic)))
cat(sprintf("  hash reproduces    %s\n", if (isTRUE(reproduced)) "YES" else "NO -- SEE ABOVE"))
cat(sprintf("  exclusion log      complete (%d rows, %d gate failures)\n", nrow(excl), length(hard_fail)))
cat(sprintf("  amendment rule     provenance/amendments.md (empty)\n"))
ok <- isTRUE(reproduced) && !length(missing_excl)
cat(sprintf("\n  PHASE 2 %s\n", if (ok) "CLOSES." else "DOES NOT CLOSE -- see above."))
stopifnot(nrow(analytic) == N, !anyDuplicated(analytic$ccn), ok)

hdr("done")
